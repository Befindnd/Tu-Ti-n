function getThienKiepLoai(n) {
  const t = THIEN_KIEP_LOAI.filter((t) => n >= t.yeu_cau_cap_min);
  if (0 === t.length) return THIEN_KIEP_LOAI[0];
  const e = t.map((n, t) => t + 1),
    h = e.reduce((n, t) => n + t, 0);
  let i = Math.random() * h,
    a = 0;
  for (let n = 0; n < t.length; n++) if (((a += e[n]), i < a)) return t[n];
  return t[t.length - 1];
}

